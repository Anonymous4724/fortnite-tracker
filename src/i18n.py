TRANSLATIONS = {"fr": FRENCH}


def normalise(code: str | None) -> str:
    """The language actually served for a requested code."""
    code = (code or "").strip().lower()[:2]
    return code if code in LANGUAGES else DEFAULT_LANGUAGE


def translate(text: str, language: str) -> str:
    """English source string, or its translation when one exists."""
    table = TRANSLATIONS.get(normalise(language))
    return table.get(text, text) if table else text


def catalogue(language: str) -> dict:
    """The whole table, for scripts that build strings on the client side."""
    return dict(TRANSLATIONS.get(normalise(language)) or {})


def _report() -> int:
    """List the strings the templates ask for but this file does not carry."""
    import os
    import re

    asked: set[str] = set()
    # _("...") in the templates, T('...') in the scripts they load
    pattern = re.compile(r"""\b_\(\s*["'](.+?)["']\s*\)|\bT\(\s*["'](.+?)["']\s*\)""")
    for folder in ("templates", "static"):
        for name in sorted(os.listdir(folder)):
            if not name.endswith((".html", ".js")):
                continue
            with open(os.path.join(folder, name), encoding="utf-8") as handle:
                for hit in pattern.findall(handle.read()):
                    raw = hit[0] or hit[1]
                    asked.add(raw.replace("\\'", "'").replace('\\"', '"')
                                 .replace("\\n", "\n"))
    missing = sorted(s for s in asked if s not in FRENCH)
    print(f"{len(asked)} strings used, {len(FRENCH)} translated, {len(missing)} missing")
    for text in missing:
        print(f'    "{text}": "",')
    return 1 if missing else 0


if __name__ == "__main__":
    raise SystemExit(_report())
